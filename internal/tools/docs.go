package tools

import (
	"context"
	"encoding/json"
	"fmt"
	"io"
	"log/slog"
	"sort"
	"strings"

	"github.com/modelcontextprotocol/go-sdk/mcp"

	"github.com/salehparsa/pihole-mcp/internal/config"
	"github.com/salehparsa/pihole-mcp/internal/confirm"
	"github.com/salehparsa/pihole-mcp/internal/instances"
)

// Markdown renders the reference for every tool (with writes enabled) from the
// registered schemas, so docs/tools.md can never drift from the code.
func Markdown(ctx context.Context) (string, error) {
	cfg := config.Defaults()
	cfg.Writes.Enabled = true
	cm, err := confirm.New("docs", cfg.Writes.ConfirmTTL)
	if err != nil {
		return "", err
	}
	d := &Deps{Cfg: &cfg, Reg: instances.FromClients(nil), Confirm: cm, Version: "docs", Log: slog.New(slog.NewTextHandler(io.Discard, nil))}
	srv := New(d)
	t1, t2 := mcp.NewInMemoryTransports()
	ss, err := srv.Connect(ctx, t1, nil)
	if err != nil {
		return "", err
	}
	defer func() { _ = ss.Close() }()
	cs, err := mcp.NewClient(&mcp.Implementation{Name: "docs", Version: "0"}, nil).Connect(ctx, t2, nil)
	if err != nil {
		return "", err
	}
	defer func() { _ = cs.Close() }()

	var tools []*mcp.Tool
	for t, err := range cs.Tools(ctx, nil) {
		if err != nil {
			return "", err
		}
		tools = append(tools, t)
	}
	sort.Slice(tools, func(i, j int) bool { return tools[i].Name < tools[j].Name })

	var b strings.Builder
	b.WriteString("# Tool reference\n\n")
	b.WriteString("<!-- Generated by `pihole-mcp docs`. Do not edit by hand. -->\n\n")
	b.WriteString("Every tool accepts an optional `instance`. Read tools are always available; change tools (marked **writes**) are registered only when `writes.enabled` is true and are two-step: call without `confirm_token` to preview, then repeat with the returned token.\n\n")
	b.WriteString("| Tool | Kind | Summary |\n|---|---|---|\n")
	for _, t := range tools {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %s |\n", t.Name, t.Name, kind(t), oneLine(t.Title))
	}
	for _, t := range tools {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\n**Kind:** %s\n\n", t.Name, t.Description, kind(t))
		raw, _ := json.Marshal(t.InputSchema)
		var schema struct {
			Properties map[string]struct {
				Type        any    `json:"type"`
				Description string `json:"description"`
			} `json:"properties"`
			Required []string `json:"required"`
		}
		_ = json.Unmarshal(raw, &schema)
		if len(schema.Properties) == 0 {
			b.WriteString("_No arguments._\n")
			continue
		}
		req := map[string]bool{}
		for _, r := range schema.Required {
			req[r] = true
		}
		names := make([]string, 0, len(schema.Properties))
		for n := range schema.Properties {
			names = append(names, n)
		}
		sort.Strings(names)
		b.WriteString("| Argument | Type | Required | Description |\n|---|---|---|---|\n")
		for _, n := range names {
			p := schema.Properties[n]
			fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", n, typeName(p.Type), map[bool]string{true: "yes", false: ""}[req[n]], oneLine(p.Description))
		}
	}
	return b.String(), nil
}

func kind(t *mcp.Tool) string {
	if t.Annotations != nil && t.Annotations.ReadOnlyHint {
		return "read-only"
	}
	return "**writes**"
}

func typeName(t any) string {
	switch v := t.(type) {
	case string:
		return v
	case []any:
		var s []string
		for _, x := range v {
			if x != "null" {
				s = append(s, fmt.Sprint(x))
			}
		}
		return strings.Join(s, "/")
	}
	return ""
}

func oneLine(s string) string { return strings.ReplaceAll(strings.TrimSpace(s), "\n", " ") }
