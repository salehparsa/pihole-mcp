#!/usr/bin/env python3
"""Regenerate THIRD_PARTY_LICENSES.md from the modules linked into the binary."""
import glob, os, subprocess, sys

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
out = subprocess.run(["go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}", "./cmd/pihole-mcp"],
                     cwd=root, capture_output=True, text=True, check=True).stdout
mods = sorted({tuple(l.split(" ", 2)) for l in out.splitlines() if l.strip()})
parts = ["# Third-party licenses\n\nThe pihole-mcp binary and container image include the following open-source modules. "
         "Their copyright notices and license texts are reproduced below as their licenses require. "
         "pihole-mcp itself is licensed under Apache-2.0 (see `LICENSE`).\n\n"
         "<!-- Generated by scripts/gen-third-party.py (make licenses). Do not edit by hand. -->\n"]
for path, ver, d in mods:
    files = sorted(f for f in glob.glob(os.path.join(d, "*")) if os.path.basename(f).upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE")) and os.path.isfile(f))
    parts.append(f"\n---\n\n## {path} {ver}\n")
    if not files:
        sys.exit(f"no license file found for {path}")
    for f in files:
        parts.append(f"\n### {os.path.basename(f)}\n\n```text\n{open(f, encoding='utf-8', errors='replace').read().strip()}\n```\n")
goroot = subprocess.run(["go", "env", "GOROOT"], capture_output=True, text=True, check=True).stdout.strip()
parts.append("\n---\n\n## Go standard library and runtime\n\n### LICENSE\n\n```text\n" + open(os.path.join(goroot, "LICENSE")).read().strip() + "\n```\n")
open(os.path.join(root, "THIRD_PARTY_LICENSES.md"), "w").write("".join(parts))
print(f"wrote THIRD_PARTY_LICENSES.md for {len(mods)} modules")
